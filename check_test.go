func TestViolationString(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	v := Violation{File: filepath.Join(dir, "a.go"), Line: 3, Message: "boom"}
	if got, want := v.String(), "a.go:3: boom"; got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
	// Outside the working directory, the path stays absolute.
	v.File = filepath.Join(dir, "sub", "..", "..", "elsewhere.go")
	if got := v.String(); !strings.HasPrefix(got, string(filepath.Separator)) {
		t.Fatalf("got %q, want an absolute path", got)
	}
}

func TestReceiverTypeName(t *testing.T) {
	cases := []struct {
		src  string
		want string
	}{
		{"func (f Foo) M() {}", "Foo"},
		{"func (f *Foo) M() {}", "Foo"},
		{"func (f Foo[T]) M() {}", "Foo"},
		{"func (f Foo[T, U]) M() {}", "Foo"},
		{"func (f pkg.Foo) M() {}", ""},
	}
	for _, c := range cases {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, "a.go", "package p\n\n"+c.src, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		var got string
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok {
				got = receiverTypeName(fn.Recv.List[0].Type)
			}
		}
		if got != c.want {
			t.Errorf("%s: got %q, want %q", c.src, got, c.want)
		}
	}
}

func TestHasBuildConstraint(t *testing.T) {
	cases := []struct {
		src  string
		want bool
	}{
		{"package p\n", false},
		{"//go:build linux\n\npackage p\n", true},
		{"// +build linux\n\npackage p\n", false},
		{"// just a comment\n\npackage p\n", false},
	}
	for _, c := range cases {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, "a.go", c.src, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		if got := hasBuildConstraint(f); got != c.want {
			t.Errorf("%q: got %v, want %v", c.src, got, c.want)
		}
	}
}

func TestCleanPath(t *testing.T) {
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if got, want := cleanPath("a.go"), filepath.Join(wd, "a.go"); got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
	if got, want := cleanPath(filepath.Join(wd, "b", "..", "c.go")), filepath.Join(wd, "c.go"); got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
}
